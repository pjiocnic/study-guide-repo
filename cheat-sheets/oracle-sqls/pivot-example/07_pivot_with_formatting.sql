
SELECT
  team,
  TO_CHAR(GAME1, '999G999') AS GAME1,
  TO_CHAR(GAME2, '999G999') AS GAME2,
  TO_CHAR(GAME3, '999G999') AS GAME3,
  TO_CHAR(GAME4, '999G999') AS GAME4,

  -- Compute total
  TO_CHAR(GAME1 + GAME2 + GAME3 + NVL(GAME4, 0), '999G999') AS TOTAL,

  -- Percentages
  ROUND(GAME1 * 100 / NULLIF((GAME1 + GAME2 + GAME3 + NVL(GAME4, 0)), 0), 2) AS GAME1_PCT,
  ROUND(GAME2 * 100 / NULLIF((GAME1 + GAME2 + GAME3 + NVL(GAME4, 0)), 0), 2) AS GAME2_PCT,
  ROUND(GAME3 * 100 / NULLIF((GAME1 + GAME2 + GAME3 + NVL(GAME4, 0)), 0), 2) AS GAME3_PCT,
  ROUND(GAME4 * 100 / NULLIF((GAME1 + GAME2 + GAME3 + NVL(GAME4, 0)), 0), 2) AS GAME4_PCT

FROM (
  SELECT *
  FROM (
    SELECT team, game, score
    FROM team_scores
  )
  PIVOT (
    MAX(score)
    FOR game IN (
      'GAME1' AS GAME1,
      'GAME2' AS GAME2,
      'GAME3' AS GAME3,
      'GAME4' AS GAME4
    )
  )
)
ORDER BY team;
