def _version_tuple(v):
    # robust parse (handles "2.1.1", "2.0.0rc2", etc.)
    parts = []
    for p in v.split("."):
        num = "".join(ch for ch in p if ch.isdigit())
        parts.append(int(num) if num else 0)
    return tuple(parts[:3] + [0]*(3-len(parts)))

